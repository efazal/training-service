"""Discover managed MLflow and reserve one durable run per accepted submission."""

from __future__ import annotations

import json
import logging
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import quote, urlencode

from kubernetes import client, config
from kubernetes.client.exceptions import ApiException
from kubernetes.config.config_exception import ConfigException
from urllib3.exceptions import HTTPError

from training_service.errors import ApiError
from training_service.kubernetes_client import TIMEOUT
from training_service.metrics.client import TrackingClient, TrackingError, valid_url

LOG = logging.getLogger(__name__)
ANNOTATION = "training.rhoai.io/mlflow"


def unavailable() -> ApiError:
    return ApiError(
        503,
        "metrics_unavailable",
        "MLflow tracking is unavailable. Ask the administrator to check the MLflow server, "
        "project workspace, training service account permissions and trusted certificates.",
    )


def discover() -> str | None:
    """Read the singleton's published endpoint; a DSC flag alone is not readiness."""
    if os.getenv("TRAINING_SERVICE_MLFLOW_ENABLED", "false").lower() != "true":
        return None
    try:
        configuration = client.Configuration()
        config.load_incluster_config(client_configuration=configuration)
        configuration.retries = 0
        with client.ApiClient(configuration) as api:
            resource = client.CustomObjectsApi(api).get_cluster_custom_object(
                "mlflow.opendatahub.io", "v1", "mlflows", "mlflow", _request_timeout=TIMEOUT
            )
    except ApiException as error:
        if error.status == 404:
            return None
        raise unavailable() from None
    except (ConfigException, HTTPError, OSError):
        raise unavailable() from None
    status = resource.get("status", {})
    if not any(
        condition.get("type") == "Available"
        and condition.get("status") == "True"
        and condition.get("observedGeneration", resource["metadata"].get("generation"))
        == resource["metadata"].get("generation")
        for condition in status.get("conditions", [])
    ):
        raise unavailable()
    uri = status.get("url")
    if not isinstance(uri, str) or not valid_url(uri):
        raise unavailable()
    return uri


def verify_training_access(project: str) -> None:
    """Check namespace service accounts, including identities generated by Ray."""
    try:
        configuration = client.Configuration()
        config.load_incluster_config(client_configuration=configuration)
        configuration.retries = 0
        with client.ApiClient(configuration) as api:
            auth = client.AuthorizationV1Api(api)
            for verb in ("get", "create", "update"):
                result = auth.create_subject_access_review(
                    client.V1SubjectAccessReview(
                        spec=client.V1SubjectAccessReviewSpec(
                            groups=[
                                "system:serviceaccounts",
                                f"system:serviceaccounts:{project}",
                                "system:authenticated",
                            ],
                            resource_attributes=client.V1ResourceAttributes(
                                namespace=project,
                                group="mlflow.kubeflow.org",
                                resource="experiments",
                                verb=verb,
                            ),
                        )
                    ),
                    _request_timeout=TIMEOUT,
                )
                if not result.status or not result.status.allowed or result.status.evaluation_error:
                    raise ApiError(
                        403,
                        "metrics_forbidden",
                        "Training service accounts cannot write MLflow experiments in this "
                        "project. Ask an administrator to grant the project's service-account "
                        "group MLflow integration access; see the metrics installation guide.",
                    )
    except (ApiException, ConfigException, HTTPError, OSError):
        raise unavailable() from None


def metadata(job: dict[str, Any], project: str) -> dict[str, str] | None:
    raw = job.get("metadata", {}).get("annotations", {}).get(ANNOTATION)
    if not isinstance(raw, str) or len(raw) > 4096:
        return None
    try:
        value = json.loads(raw)
        if (
            not isinstance(value, dict)
            or value.get("project") != project
            or not isinstance(value.get("run_id"), str)
            or not re.fullmatch(r"[a-f0-9]{32}", value["run_id"])
            or not isinstance(value.get("url"), str)
            or not valid_url(value.get("tracking_uri", ""))
        ):
            return None
        uri = value["tracking_uri"].rstrip("/")
        experiment_id = str(value["experiment_id"])
        if not re.fullmatch(r"[0-9]+", experiment_id):
            return None
        expected = (
            uri
            + "?"
            + urlencode({"workspace": project})
            + "#/experiments/"
            + experiment_id
            + "/runs/"
            + value["run_id"]
        )
        return value if value["url"] == expected else None
    except (ValueError, KeyError, TypeError):
        return None


def finalize_deleted(
    job: dict[str, Any],
    project: str,
    token: str,
    ca_file: str | None,
) -> None:
    value = metadata(job, project)
    if not value:
        return
    # Never forward a credential to a URL supplied only through a mutable job annotation.
    uri = discover()
    if not uri or uri.rstrip("/") != value["tracking_uri"].rstrip("/"):
        raise unavailable()
    tracking = TrackingClient(uri, project, lambda: token.removeprefix("Bearer "), ca_file=ca_file)
    info = tracking.request("GET", "runs/get", {"run_id": value["run_id"]})["run"]["info"]
    if info["status"] not in {"FINISHED", "FAILED", "KILLED"}:
        state = job.get("status", {}).get("jobStatus")
        status = {"SUCCEEDED": "FINISHED", "FAILED": "FAILED"}.get(state, "KILLED")
        tracking.log(value["run_id"], tags={"training.phase": "deleted"})
        tracking.finish(value["run_id"], status)


@dataclass(frozen=True)
class TrackedRun:
    client: TrackingClient
    run_id: str
    experiment_id: str
    experiment_name: str

    def metadata(self) -> dict[str, str]:
        return {
            "run_id": self.run_id,
            "experiment_id": self.experiment_id,
            "experiment_name": self.experiment_name,
            "url": self.client.uri
            + "?"
            + urlencode({"workspace": self.client.project})
            + "#/experiments/"
            + quote(self.experiment_id, safe="")
            + "/runs/"
            + self.run_id,
        }

    def configuration(self, ca_file: str | None) -> dict[str, str]:
        return {
            **self.metadata(),
            "tracking_uri": self.client.uri,
            "project": self.client.project,
            "ca_bundle": Path(ca_file).read_text() if ca_file else "",
        }

    def failed_submission(self) -> None:
        try:
            self.client.log(self.run_id, tags={"training.phase": "submission_failed"})
            self.client.finish(self.run_id, "FAILED")
        except TrackingError:
            LOG.warning("Could not mark the MLflow run as failed after submission failure.")


def reserve(
    uri: str,
    project: str,
    token: str,
    experiment: str | None,
    name: str,
    algorithm: str,
    submitted_by: str,
    resources: dict[str, Any],
    *,
    ca_file: str | None = None,
    parameters: dict[str, Any] | None = None,
    details: dict[str, str] | None = None,
) -> TrackedRun:
    """Use only the caller identity, with workspace forced to the path project."""
    tracking = TrackingClient(uri, project, lambda: token.removeprefix("Bearer "), ca_file=ca_file)
    try:
        experiment_name = experiment or "Default"
        experiment_id = tracking.experiment(experiment_name)
        run_id = tracking.create_run(
            experiment_id,
            name,
            {
                "training.project": project,
                "training.job_id": name,
                "training.algorithm": algorithm,
                "training.submitted_by": submitted_by,
                "training.phase": "submitted",
                "training.backend": "ray",
            },
        )
        run = TrackedRun(tracking, run_id, experiment_id, experiment_name)
        try:
            params = {"resources." + k: str(v) for k, v in resources.items()}
            params.update(details or {})
            for key, value in (parameters or {}).items():
                if len(params) >= 100:
                    break
                if (
                    isinstance(value, (str, int, float, bool))
                    and len(str(value)) <= 500
                    and not re.search(
                        r"secret|password|credential|api[_-]?key|access[_-]?key|(^|_)token($|_)",
                        key,
                        re.I,
                    )
                ):
                    params["algorithm." + key] = str(value)
            tracking.log(run_id, params=params)
        except TrackingError:
            run.failed_submission()
            raise
        return run
    except TrackingError as error:
        if error.status in {401, 403}:
            raise ApiError(
                error.status,
                "forbidden" if error.status == 403 else "unauthorized",
                "Caller cannot write MLflow experiments in this project. "
                "Check project access and sign in again if the token has expired.",
            ) from None
        raise unavailable() from None
